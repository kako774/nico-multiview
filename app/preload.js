'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('mv', {
  load: () => ipcRenderer.invoke('mv:load'),
  save: state => ipcRenderer.send('mv:save', state),
  sync: (rects, audioId, playerOnly, volumes, hides) => ipcRenderer.send('mv:sync', rects, audioId, playerOnly, volumes, hides),
  reload: id => ipcRenderer.send('mv:reload', id),
  external: id => ipcRenderer.send('mv:external', id),
  auth: () => ipcRenderer.invoke('mv:auth'),
  login: () => ipcRenderer.send('mv:login'),
  logout: () => ipcRenderer.send('mv:logout'),
  onAuth: cb => ipcRenderer.on('mv:auth', (_e, v) => cb(!!v)),
  comment: (id, text, use184) => ipcRenderer.invoke('mv:comment', id, text, use184),
  search: q => ipcRenderer.invoke('mv:search', q),
  evList: keys => ipcRenderer.invoke('mv:ev-list', keys),
  evTop: (key, n) => ipcRenderer.invoke('mv:ev-top', key, n),
  menuOpen: (type, anchor, data) => ipcRenderer.send('mv:menu-open', type, anchor, data),
  menuClose: force => ipcRenderer.send('mv:menu-close', !!force),
  menuData: data => ipcRenderer.send('mv:menu-data', data),
  onMenuAct: cb => ipcRenderer.on('mv:menu-act', (_e, a, p) => cb(a, p)),
  onMenuClosed: cb => ipcRenderer.on('mv:menu-closed', (_e, t) => cb(t)),
  onAdd: cb => ipcRenderer.on('mv:add', (_e, t) => cb(t)),
  player: (id, act) => ipcRenderer.send('mv:player', id, act),
  giftOpen: id => ipcRenderer.send('mv:gift-open', id || ''),
  giftTargets: list => ipcRenderer.send('mv:gift-targets', list),
  updateCheck: () => ipcRenderer.invoke('mv:update-check'),
  openRelease: () => ipcRenderer.send('mv:open-release'),
  version: () => ipcRenderer.invoke('mv:version'),
  overlay: (on, rect) => ipcRenderer.send('mv:overlay', !!on, rect),
  onFocus: cb => ipcRenderer.on('mv:focus', (_e, id) => cb(id)),
  onUnfocus: cb => ipcRenderer.on('mv:unfocus', () => cb()),
  onClean: cb => ipcRenderer.on('mv:clean', (_e, v) => cb(!!v)),
  cleanState: on => ipcRenderer.send('mv:clean-state', !!on),
  fullscreen: on => ipcRenderer.send('mv:fullscreen', on),
  onFullscreen: cb => ipcRenderer.on('mv:fs', (_e, v) => cb(!!v)),
  setTheme: t => ipcRenderer.send('mv:theme', t),
  openViewer: () => ipcRenderer.send('mv:open-viewer'),
  dragStart: id => ipcRenderer.send('mv:drag-start', id),
  dragEnd: () => ipcRenderer.send('mv:drag-end'),
  onDrag: cb => ipcRenderer.on('mv:drag', (_e, d) => cb(d)),
  onInfo: cb => ipcRenderer.on('mv:info', (_e, id, info) => cb(id, info)),
});
